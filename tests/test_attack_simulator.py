"""
Safe Localhost Attack Simulator for Intelligent NIDS Verification.

STRICT SAFETY BOUNDARY:
All traffic generated by this script is strictly directed to localhost (127.0.0.1)
via the Npcap Loopback Adapter. It will never emit disruptive packets to external,
public, or production networks.
"""

import sys
import os
import time
import argparse
from typing import List

# Ensure project root is in sys.path
PROJECT_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
if PROJECT_ROOT not in sys.path:
    sys.path.insert(0, PROJECT_ROOT)

from scapy.all import send, IP, TCP, ICMP, conf
from core.network_utils import is_admin

# Strict safety whitelist
ALLOWED_TARGETS = {"127.0.0.1", "localhost", "192.168.56.1"}


def validate_target(target_ip: str) -> bool:
    """Ensure the target destination is within the authorized isolated test boundary."""
    if target_ip not in ALLOWED_TARGETS and not target_ip.startswith("127."):
        print(f"[SECURITY BLOCKED] Refusing to target '{target_ip}'.")
        print("  Attack simulations are strictly permitted on localhost (127.0.0.1) only.")
        return False
    return True


def simulate_port_scan(target: str = "127.0.0.1", start_port: int = 20, end_port: int = 40):
    """Simulate a rapid TCP Port Scan by sending SYN packets to sequential ports."""
    print(f"[*] [TEST SCENARIO 1] Simulating Port Scan against {target} (Ports {start_port}-{end_port})...")
    sent = 0
    for port in range(start_port, end_port + 1):
        pkt = IP(dst=target) / TCP(dport=port, flags="S")
        send(pkt, verbose=False)
        sent += 1
        time.sleep(0.02)  # fast 20ms pacing
    print(f"[+] Sent {sent} port-scan packets.")


def simulate_syn_flood(target: str = "127.0.0.1", target_port: int = 80, count: int = 60):
    """Simulate a brief, controlled TCP SYN Flood burst."""
    print(f"[*] [TEST SCENARIO 2] Simulating SYN Flood burst ({count} packets) against {target}:{target_port}...")
    sent = 0
    for i in range(count):
        # Varying source ports to simulate multiple half-open connection attempts
        pkt = IP(dst=target) / TCP(sport=10000 + (i % 5000), dport=target_port, flags="S")
        send(pkt, verbose=False)
        sent += 1
        time.sleep(0.01)  # 10ms pacing
    print(f"[+] Sent {sent} SYN flood packets.")


def simulate_icmp_flood(target: str = "127.0.0.1", count: int = 50):
    """Simulate an ICMP Ping Flood burst."""
    print(f"[*] [TEST SCENARIO 3] Simulating ICMP Ping Flood burst ({count} packets) against {target}...")
    sent = 0
    for _ in range(count):
        pkt = IP(dst=target) / ICMP(type=8, code=0)
        send(pkt, verbose=False)
        sent += 1
        time.sleep(0.01)  # 10ms pacing
    print(f"[+] Sent {sent} ICMP ping packets.")


def simulate_stealth_xmas(target: str = "127.0.0.1", target_port: int = 80):
    """Simulate a stealth TCP Xmas Scan packet (FIN+PSH+URG)."""
    print(f"[*] [TEST SCENARIO 4] Sending Stealth TCP Xmas Scan packet to {target}:{target_port}...")
    pkt = IP(dst=target) / TCP(dport=target_port, flags="FPU")
    send(pkt, verbose=False)
    print("[+] Sent 1 Xmas packet.")


def simulate_suspicious_port(target: str = "127.0.0.1", target_port: int = 4444):
    """Simulate connection to a high-risk exploit/backdoor port (e.g. Metasploit 4444)."""
    print(f"[*] [TEST SCENARIO 5] Sending probe to known exploit/backdoor port {target}:{target_port}...")
    pkt = IP(dst=target) / TCP(dport=target_port, flags="S")
    send(pkt, verbose=False)
    print("[+] Sent 1 probe packet.")


def main():
    parser = argparse.ArgumentParser(description="Intelligent NIDS - Safe Localhost Attack Simulator")
    parser.add_argument(
        "--attack",
        choices=["portscan", "synflood", "icmpflood", "xmas", "suspicious", "all"],
        default="all",
        help="Attack scenario to simulate (default: all)",
    )
    parser.add_argument(
        "--target",
        default="127.0.0.1",
        help="Target IP address (Strictly localhost only)",
    )

    args = parser.parse_args()

    if not validate_target(args.target):
        sys.exit(1)

    print("=" * 65)
    print(" INTELLIGENT NIDS - SAFE LOCALHOST ATTACK SIMULATOR")
    print(f" Target Bound: {args.target} (Isolated Test Environment)")
    print("=" * 65)

    if not is_admin():
        print("[WARN] Running as Standard User. Sending raw packets may require Administrator.")

    attack = args.attack.lower()

    if attack in ["portscan", "all"]:
        simulate_port_scan(args.target)
        if attack == "all":
            time.sleep(1.0)

    if attack in ["synflood", "all"]:
        simulate_syn_flood(args.target)
        if attack == "all":
            time.sleep(1.0)

    if attack in ["icmpflood", "all"]:
        simulate_icmp_flood(args.target)
        if attack == "all":
            time.sleep(1.0)

    if attack in ["xmas", "all"]:
        simulate_stealth_xmas(args.target)
        if attack == "all":
            time.sleep(1.0)

    if attack in ["suspicious", "all"]:
        simulate_suspicious_port(args.target)

    print("\n[SUCCESS] Simulation completed safely on localhost.")
    print("=" * 65)


if __name__ == "__main__":
    main()
